import { describe, expect, it } from 'vitest';
import { mkdir, mkdtemp, rm, symlink, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { walkNodeModules, claim, dedupeByShallowest } from '../src/parsers/node_modules.js';
import { detectLockfile, scanLockfile } from '../src/parsers/index.js';
import { PatchstackError } from '../src/types.js';

const here = path.dirname(fileURLToPath(import.meta.url));
const bunProject = path.join(here, 'fixtures', 'bun-project');

describe('walkNodeModules', () => {
  it('extracts every package.json with a name and version', async () => {
    const entries = await walkNodeModules(bunProject);
    const names = entries.map((e) => `${e.name}@${e.version}`).sort();
    expect(names).toEqual(
      [
        '@scope/pkg@2.1.0',
        'axios@1.6.0',
        'lodash@4.17.21',
        'nested-helper@0.3.2',
      ].sort(),
    );
  });

  it('marks top-level packages as direct and nested ones as not', async () => {
    const entries = await walkNodeModules(bunProject);
    const axios = entries.find((e) => e.name === 'axios');
    const nested = entries.find((e) => e.name === 'nested-helper');
    expect(axios?.direct).toBe(true);
    expect(nested?.direct).toBe(false);
  });

  it('skips .bin and other dotfiles', async () => {
    const entries = await walkNodeModules(bunProject);
    expect(entries.find((e) => e.name === 'some-stub')).toBeUndefined();
    expect(entries.find((e) => e.name?.startsWith('.'))).toBeUndefined();
  });

  it('handles scoped packages', async () => {
    const entries = await walkNodeModules(bunProject);
    const scoped = entries.find((e) => e.name === '@scope/pkg');
    expect(scoped?.version).toBe('2.1.0');
  });

  it('throws LOCKFILE_NOT_FOUND when there is no node_modules', async () => {
    const cwd = await mkdtemp(path.join(tmpdir(), 'patchstack-connect-nm-'));
    try {
      await expect(walkNodeModules(cwd)).rejects.toMatchObject({
        code: 'LOCKFILE_NOT_FOUND',
      });
    } finally {
      await rm(cwd, { recursive: true, force: true });
    }
  });

  it('terminates on symlinks that point back up the tree', async () => {
    // Symlinks are followed now, because an isolated install makes every top-level package one and refusing
    // them found nothing at all there. The cycle safety that refusing them provided comes from real paths
    // instead: a target already visited is not visited again, so a loop ends rather than repeating.
    //
    // Two links to the same place, both resolving to the project root, which contains no package manifest.
    const cwd = await mkdtemp(path.join(tmpdir(), 'patchstack-connect-nm-cycle-'));
    try {
      await writeFile(
        path.join(cwd, 'package.json'),
        JSON.stringify({ name: 'root-project', version: '1.0.0' }),
      );
      await mkdir(path.join(cwd, 'node_modules'));
      await symlink('..', path.join(cwd, 'node_modules', 'loop-a'));
      await symlink('..', path.join(cwd, 'node_modules', 'loop-b'));

      await expect(walkNodeModules(cwd)).resolves.toEqual([]);
    } finally {
      await rm(cwd, { recursive: true, force: true });
    }
  });

  it('reads a package reached through a symlink', async () => {
    // The other half, and the reason the rule changed: in an isolated layout this is the only way the
    // package is reachable at all.
    const cwd = await mkdtemp(path.join(tmpdir(), 'patchstack-connect-nm-link-'));
    try {
      await writeFile(path.join(cwd, 'package.json'), JSON.stringify({ name: 'root', version: '1.0.0' }));
      await mkdir(path.join(cwd, 'store', 'real'), { recursive: true });
      await writeFile(
        path.join(cwd, 'store', 'real', 'package.json'),
        JSON.stringify({ name: 'real', version: '2.3.4' }),
      );
      await mkdir(path.join(cwd, 'node_modules'));
      await symlink(path.join(cwd, 'store', 'real'), path.join(cwd, 'node_modules', 'real'), 'dir');

      // The LINK location, not the store target it resolves to. Node resolves an import by walking up
      // from the importing file looking for `node_modules/<name>`, so the link is the path an import
      // actually travels through — and the path a lockfile would name. Reporting the store target would
      // describe where the bytes live, which no resolver ever consults.
      await expect(walkNodeModules(cwd)).resolves.toEqual([
        { name: 'real', version: '2.3.4', path: 'node_modules/real', direct: true },
      ]);
    } finally {
      await rm(cwd, { recursive: true, force: true });
    }
  });
});

describe('detectLockfile for bun', () => {
  it('detects bun.lockb and routes to the node-modules walk', async () => {
    const detected = await detectLockfile(bunProject);
    expect(detected.filename).toBe('bun.lockb');
    expect(detected.strategy).toBe('node-modules-walk');
    expect(detected.ecosystem).toBe('npm');
  });
});

describe('scanLockfile for bun.lockb', () => {
  it('returns a manifest built from the node_modules walk', async () => {
    const manifest = await scanLockfile(bunProject);
    expect(manifest.ecosystem).toBe('npm');
    const names = manifest.packages.map((p) => p.name).sort();
    expect(names).toEqual(['@scope/pkg', 'axios', 'lodash', 'nested-helper']);
  });
});

describe('reading the tree concurrently', () => {
  it('gives the same manifest every time, in the same order', async () => {
    // The reads happen in parallel now, so the order they FINISH in must not be the order they are
    // reported in: a manifest whose contents shift between runs makes a build fingerprint useless.
    const dir = await mkdtemp(path.join(tmpdir(), 'ps-walk-order-'));
    try {
      await Promise.all(
        Array.from({ length: 40 }, async (_unused, i) => {
          const pkg = path.join(dir, 'node_modules', `pkg-${i}`);
          await mkdir(pkg, { recursive: true });
          await writeFile(path.join(pkg, 'package.json'), JSON.stringify({ name: `pkg-${i}`, version: `1.0.${i}` }));
          // A nested dependency each, so the walk recurses while other branches are still being read.
          const nested = path.join(pkg, 'node_modules', `dep-${i}`);
          await mkdir(nested, { recursive: true });
          await writeFile(path.join(nested, 'package.json'), JSON.stringify({ name: `dep-${i}`, version: '2.0.0' }));
        }),
      );

      const first = await walkNodeModules(dir);
      const second = await walkNodeModules(dir);

      expect(first).toEqual(second);
      expect(first).toHaveLength(80);
      // And each package once: a real path is claimed in one synchronous step, so two concurrent readers
      // cannot both take it.
      expect(new Set(first.map((entry) => `${entry.name}@${entry.version}`)).size).toBe(80);
    } finally {
      await rm(dir, { recursive: true, force: true });
    }
  });
  it('marks a package direct on an isolated layout', async () => {
    // The layout the ambiguity lives in: one package, two paths — the top-level symlink, which is a direct
    // dependency, and the copy inside the store, which is a level deeper. Whichever path is reached first
    // used to own `direct`, which under concurrent reads is not a property of the project. What decides it
    // is pinned by the two tests below; this one is the layout end to end.
    const dir = await mkdtemp(path.join(tmpdir(), 'ps-walk-direct-'));
    try {
      const names = Array.from({ length: 24 }, (_unused, i) => `pkg-${i}`);
      for (const name of names) {
        const store = path.join(dir, 'node_modules', '.bun', `${name}@1.0.0`, 'node_modules', name);
        await mkdir(store, { recursive: true });
        await writeFile(path.join(store, 'package.json'), JSON.stringify({ name, version: '1.0.0' }));
        await symlink(store, path.join(dir, 'node_modules', name), 'dir');
      }

      const entries = await walkNodeModules(dir);

      expect(entries).toHaveLength(names.length);
      expect(entries.every((entry) => entry.direct === true)).toBe(true);
    } finally {
      await rm(dir, { recursive: true, force: true });
    }
  });

  it('lets a shallower arrival re-claim a real path, and nothing else', async () => {
    // What makes the answer independent of arrival order. A repeat at the same depth or deeper is a cycle
    // or a duplicate and is refused, so the walk still terminates; a strictly shallower one is a better
    // answer about the same package and is let through.
    const dir = await mkdtemp(path.join(tmpdir(), 'ps-walk-claim-'));
    try {
      const pkg = path.join(dir, 'pkg');
      await mkdir(pkg, { recursive: true });
      const seen = new Map<string, number>();

      expect(await claim(pkg, seen, 2)).not.toBeNull();
      expect(await claim(pkg, seen, 2), 'same depth').toBeNull();
      expect(await claim(pkg, seen, 3), 'deeper').toBeNull();
      expect(await claim(pkg, seen, 1), 'shallower').not.toBeNull();
      expect(await claim(pkg, seen, 1), 'shallower, then repeated').toBeNull();
    } finally {
      await rm(dir, { recursive: true, force: true });
    }
  });

  it('keeps the shallowest finding of a package whichever order they arrive in', () => {
    // The other half. Two findings of one real path disagree about `direct`, and the depth decides — not
    // the position in the list, which is what an asynchronous walk makes arbitrary.
    const deep = { entry: { name: 'shared', version: '1.0.0', direct: false }, realpath: '/store/shared', depth: 1 };
    const shallow = { entry: { name: 'shared', version: '1.0.0', direct: true }, realpath: '/store/shared', depth: 0 };

    expect(dedupeByShallowest([deep, shallow])).toEqual([shallow.entry]);
    expect(dedupeByShallowest([shallow, deep])).toEqual([shallow.entry]);
  });
});
