import { lstat, readFile, readdir, realpath, stat } from 'node:fs/promises';
import path from 'node:path';
import { PatchstackError, type PackageEntry } from '../types.js';

/**
 * Dot-directories that hold real packages rather than caches.
 *
 * Skipping every dotfile is right for `.cache` and `.bin`; it is wrong for `.bun` and `.pnpm`, which is
 * where an isolated install actually keeps the packages. A project scanned that way reports no packages at
 * all, and an empty inventory reads exactly like a project with nothing vulnerable in it.
 */
const PACKAGE_STORE_DIRS = new Set(['.bun', '.pnpm', '.store']);

export async function walkNodeModules(cwd: string): Promise<PackageEntry[]> {
  const root = path.join(cwd, 'node_modules');

  try {
    const info = await stat(root);
    if (!info.isDirectory()) {
      throw new PatchstackError(
        `${root} exists but is not a directory.`,
        'LOCKFILE_NOT_FOUND',
      );
    }
  } catch (cause) {
    if (cause instanceof PatchstackError) {
      throw cause;
    }
    throw new PatchstackError(
      `node_modules/ not found at ${cwd}. Install dependencies first (e.g. \`bun install\` or \`npm install\`).`,
      'LOCKFILE_NOT_FOUND',
      cause,
    );
  }

  // The shallowest depth each real path has been reached at. An isolated layout is symlinks into a store,
  // so the same package is reachable by several paths — and following symlinks without this is how a walk
  // stops terminating.
  //
  // A DEPTH rather than a visited flag, because depth is what decides `direct`, and the two paths to one
  // package do not agree about it: the top-level symlink is depth 0 and the copy inside the store is
  // deeper. With a flag, whichever traversal arrived first owned the answer — which under concurrent reads
  // is not the same answer twice. Re-traversal is allowed only when strictly shallower, so it terminates.
  //
  // Seeded with the project itself, because a link pointing back up the tree resolves there: followed, the
  // project's own manifest would be read as one of its dependencies. A project is not installed into itself.
  const seen = new Map<string, number>();
  try {
    seen.set(await realpath(cwd), -1);
  } catch {
    // Unresolvable cwd. The walk still terminates on every other repeated path.
  }

  return dedupeByShallowest(await walk(root, 0, seen));
}

/**
 * One entry per real path, at the shallowest depth it was found.
 *
 * The traversal can emit a package twice — once through a top-level symlink and once inside the store it
 * points into — and the two differ in `direct`. Resolved here rather than during the walk so the answer
 * does not depend on which asynchronous read finished first.
 */
export function dedupeByShallowest(found: Found[]): PackageEntry[] {
  const best = new Map<string, Found>();
  for (const item of found) {
    const current = best.get(item.realpath);
    if (current === undefined || item.depth < current.depth) best.set(item.realpath, item);
  }

  return [...best.values()].map(({ entry }) => entry);
}

/**
 * A package as found, with what is needed to choose between two findings of the same one.
 *
 * Exported, with `claim` and `dedupeByShallowest`, only so the tests can pin what decides between them —
 * the walk's own ordering cannot be controlled from outside it. Not part of this package's public surface.
 */
export interface Found {
  entry: PackageEntry;
  realpath: string;
  depth: number;
}

/**
 * Directories read at a time.
 *
 * A dependency tree is thousands of tiny reads, and doing them one after another spends nearly all of the
 * scan waiting. A cap rather than everything at once: an unbounded fan-out over a large tree opens more file
 * handles than the process is allowed and the scan fails with EMFILE.
 */
const CONCURRENCY = 32;

async function walk(dir: string, depth: number, seen: Map<string, number>): Promise<Found[]> {
  let names: string[];
  try {
    names = await readdir(dir);
  } catch {
    return [];
  }

  // Results are collected per entry and concatenated in directory order, so reading concurrently does not
  // make the manifest depend on which read finished first.
  const perEntry = await mapLimit(names, async (name) => {
    if (name.startsWith('.') && !PACKAGE_STORE_DIRS.has(name)) return [];

    const fullPath = path.join(dir, name);
    const resolved = await claim(fullPath, seen, depth);
    if (resolved === null) return [];

    // A store directory holds packages one level down and is not itself a package: descend without trying
    // to read a manifest from it, and without counting its depth against the direct-dependency marker.
    if (PACKAGE_STORE_DIRS.has(name)) return walk(fullPath, depth, seen);

    if (name.startsWith('@')) {
      let subNames: string[];
      try {
        subNames = await readdir(fullPath);
      } catch {
        return [];
      }

      const scoped = await mapLimit(subNames, async (sub) => {
        if (sub.startsWith('.')) return [];
        const scopedDir = path.join(fullPath, sub);
        const scopedReal = await claim(scopedDir, seen, depth);
        if (scopedReal === null) return [];

        return packageAndNested(scopedDir, scopedReal, depth, seen);
      });

      return scoped.flat();
    }

    return packageAndNested(fullPath, resolved, depth, seen);
  });

  return perEntry.flat();
}

async function packageAndNested(
  pkgDir: string,
  resolved: string,
  depth: number,
  seen: Map<string, number>,
): Promise<Found[]> {
  const [own, nested] = await Promise.all([readPackage(pkgDir, depth), walkNested(pkgDir, depth, seen)]);

  return own === null ? nested : [{ entry: own, realpath: resolved, depth }, ...nested];
}

/** `items.map(fn)` with at most `CONCURRENCY` in flight, results in input order. */
async function mapLimit<T, R>(items: T[], fn: (item: T) => Promise<R>): Promise<R[]> {
  const results = new Array<R>(items.length);
  let next = 0;
  const workers = Array.from({ length: Math.min(CONCURRENCY, items.length) }, async () => {
    while (next < items.length) {
      const index = next++;
      results[index] = await fn(items[index] as T);
    }
  });
  await Promise.all(workers);

  return results;
}

async function readPackage(pkgDir: string, depth: number): Promise<PackageEntry | null> {
  let raw: string;
  try {
    raw = await readFile(path.join(pkgDir, 'package.json'), 'utf8');
  } catch {
    return null;
  }

  let parsed: { name?: unknown; version?: unknown };
  try {
    parsed = JSON.parse(raw) as { name?: unknown; version?: unknown };
  } catch {
    return null;
  }

  if (typeof parsed.name !== 'string' || parsed.name.length === 0) {
    return null;
  }
  if (typeof parsed.version !== 'string' || parsed.version.length === 0) {
    return null;
  }

  return { name: parsed.name, version: parsed.version, direct: depth === 0 };
}

async function walkNested(pkgDir: string, depth: number, seen: Map<string, number>): Promise<Found[]> {
  const nested = path.join(pkgDir, 'node_modules');
  if ((await claim(nested, seen, depth + 1)) === null) {
    return [];
  }

  return walk(nested, depth + 1, seen);
}

/**
 * Claim a directory for traversal at `depth`, returning its real path, or null to skip it.
 *
 * Symlinks ARE followed, because an isolated install makes every top-level package one — refusing them
 * finds nothing there. The cycle risk that refusing them avoided is handled by the real path instead: a
 * target already reached at the same depth or shallower is skipped, so a link back up the tree ends the
 * walk rather than repeating it. Links pointing outside are followed too; a store lives outside
 * `node_modules` on some layouts, and the realpath map is what bounds the traversal either way.
 *
 * A strictly shallower arrival is allowed through, because it is a better answer about the same package
 * and refusing it would leave that answer to whichever read happened to finish first. Depth only ever
 * decreases on such a re-entry, so the traversal still terminates.
 *
 * The claim is made in one synchronous step after the last await, so concurrent callers cannot both take
 * it at the same depth.
 */
export async function claim(dir: string, seen: Map<string, number>, depth: number): Promise<string | null> {
  let resolved: string;
  try {
    const info = await lstat(dir);
    if (!info.isDirectory() && !info.isSymbolicLink()) return null;

    resolved = await realpath(dir);
    const target = await stat(resolved);
    if (!target.isDirectory()) return null;
  } catch {
    return null; // a broken link, or a path that vanished mid-walk
  }

  const claimed = seen.get(resolved);
  if (claimed !== undefined && claimed <= depth) return null;
  seen.set(resolved, depth);

  return resolved;
}
