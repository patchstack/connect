import { lstat, readFile, readdir, stat } from 'node:fs/promises';
import path from 'node:path';
import { PatchstackError, type PackageEntry } from '../types.js';

export async function walkNodeModules(cwd: string): Promise<PackageEntry[]> {
  const root = path.join(cwd, 'node_modules');

  try {
    const info = await stat(root);
    if (!info.isDirectory()) {
      throw new PatchstackError(
        `${root} exists but is not a directory.`,
        'LOCKFILE_NOT_FOUND',
      );
    }
  } catch (cause) {
    if (cause instanceof PatchstackError) {
      throw cause;
    }
    throw new PatchstackError(
      `node_modules/ not found at ${cwd}. Install dependencies first (e.g. \`bun install\` or \`npm install\`).`,
      'LOCKFILE_NOT_FOUND',
      cause,
    );
  }

  const entries: PackageEntry[] = [];
  await walk(root, entries, 0);
  return entries;
}

async function walk(dir: string, acc: PackageEntry[], depth: number): Promise<void> {
  let names: string[];
  try {
    names = await readdir(dir);
  } catch {
    return;
  }

  for (const name of names) {
    if (name.startsWith('.')) {
      continue;
    }

    const fullPath = path.join(dir, name);
    if (!(await isPlainDirectory(fullPath))) {
      continue;
    }

    if (name.startsWith('@')) {
      let subNames: string[];
      try {
        subNames = await readdir(fullPath);
      } catch {
        continue;
      }
      for (const sub of subNames) {
        if (sub.startsWith('.')) {
          continue;
        }
        const scopedDir = path.join(fullPath, sub);
        if (!(await isPlainDirectory(scopedDir))) {
          continue;
        }
        await readPackage(scopedDir, depth, acc);
        await walkNested(scopedDir, acc, depth);
      }
      continue;
    }

    await readPackage(fullPath, depth, acc);
    await walkNested(fullPath, acc, depth);
  }
}

async function readPackage(
  pkgDir: string,
  depth: number,
  acc: PackageEntry[],
): Promise<void> {
  let raw: string;
  try {
    raw = await readFile(path.join(pkgDir, 'package.json'), 'utf8');
  } catch {
    return;
  }

  let parsed: { name?: unknown; version?: unknown };
  try {
    parsed = JSON.parse(raw) as { name?: unknown; version?: unknown };
  } catch {
    return;
  }

  if (typeof parsed.name !== 'string' || parsed.name.length === 0) {
    return;
  }
  if (typeof parsed.version !== 'string' || parsed.version.length === 0) {
    return;
  }

  acc.push({
    name: parsed.name,
    version: parsed.version,
    direct: depth === 0,
  });
}

async function walkNested(
  pkgDir: string,
  acc: PackageEntry[],
  depth: number,
): Promise<void> {
  const nested = path.join(pkgDir, 'node_modules');
  if (!(await isPlainDirectory(nested))) {
    return;
  }
  await walk(nested, acc, depth + 1);
}

async function isPlainDirectory(dir: string): Promise<boolean> {
  try {
    const info = await lstat(dir);
    return info.isDirectory() && !info.isSymbolicLink();
  } catch {
    return false;
  }
}
